create or replace function public.create_deposit_request(
  p_amount_yer numeric,
  p_payment_method_id bigint,
  p_proof_path text,
  p_sender_name text,
  p_sender_phone text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id bigint := public.current_profile_id();
  v_rate public.exchange_rates%rowtype;
  v_method public.payment_methods%rowtype;
  v_reference text := public.make_reference('DEP');
  v_gross numeric(20,8);
  v_fee numeric(20,8);
  v_net numeric(20,8);
  v_id bigint;
begin
  if v_user_id is null then raise exception 'account_inactive'; end if;
  if p_amount_yer is null or p_amount_yer < 1000 then raise exception 'minimum_deposit_1000_yer'; end if;
  if nullif(trim(p_proof_path),'') is null then raise exception 'proof_required'; end if;

  select * into v_rate from public.exchange_rates order by rate_id limit 1;
  if v_rate.sell_rate is null or v_rate.sell_rate <= 0 then raise exception 'rate_unavailable'; end if;
  select * into v_method from public.payment_methods where method_id=p_payment_method_id and is_active=true and category in ('DEPOSIT','BOTH');
  if not found then raise exception 'payment_method_unavailable'; end if;

  v_gross := round(p_amount_yer / v_rate.sell_rate, 8);
  v_fee := round(v_gross * coalesce(v_rate.fee_percentage,0) / 100, 8);
  v_net := v_gross - v_fee;

  insert into public.deposit_requests(reference,user_id,payment_method_id,payment_method,deposit_method,amount_yer,gross_usdt,fee_usdt,net_usdt,proof_path,proof_ref,sender_name,sender_phone,status)
  values(v_reference,v_user_id,v_method.method_id,v_method.name,v_method.name,p_amount_yer,v_gross,v_fee,v_net,p_proof_path,p_proof_path,p_sender_name,p_sender_phone,'PENDING')
  returning deposit_id into v_id;

  insert into public.transactions(reference,user_id,request_id,type,status,currency,amount_usdt,amount_yer,description,metadata)
  values(v_reference,v_user_id,v_id,'DEPOSIT','PENDING','USDT',v_net,p_amount_yer,'شراء USDT عبر '||v_method.name,jsonb_build_object('rate',v_rate.sell_rate,'fee_usdt',v_fee));

  insert into public.notifications(user_id,audience,title,message,icon,reference)
  values(v_user_id,'USER','تم استلام طلب الإيداع','طلبك '||v_reference||' بانتظار مراجعة الإدارة.','fa-arrow-down',v_reference);
  insert into public.notifications(user_id,audience,title,message,icon,reference)
  values(null,'ADMIN','طلب إيداع جديد','طلب '||v_reference||' بقيمة '||round(v_net,2)||' USDT يحتاج المراجعة.','fa-file-circle-plus',v_reference);

  return jsonb_build_object('deposit_id',v_id,'reference',v_reference,'net_usdt',v_net,'status','PENDING');
end $$;

create or replace function public.create_withdraw_request(
  p_amount_usdt numeric,
  p_payout_type text,
  p_destination text,
  p_network text default null,
  p_payment_method_id bigint default null,
  p_beneficiary_name text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user public.users%rowtype;
  v_rate public.exchange_rates%rowtype;
  v_reference text := public.make_reference('WDR');
  v_fee numeric(20,8);
  v_net numeric(20,8);
  v_yer numeric(20,2);
  v_id bigint;
  v_type text := upper(p_payout_type);
begin
  select * into v_user from public.users where user_id=public.current_profile_id() for update;
  if not found then raise exception 'account_inactive'; end if;
  if upper(coalesce(v_user.kyc_status,'')) <> 'APPROVED' then raise exception 'kyc_required'; end if;
  if p_amount_usdt is null or p_amount_usdt <= 0 then raise exception 'invalid_amount'; end if;
  if coalesce(v_user.balance_usdt,0) < p_amount_usdt then raise exception 'insufficient_balance'; end if;
  if v_type not in ('EXTERNAL_USDT','YER_PAYOUT') then raise exception 'invalid_payout_type'; end if;
  if nullif(trim(p_destination),'') is null then raise exception 'destination_required'; end if;

  select * into v_rate from public.exchange_rates order by rate_id limit 1;
  if v_type = 'EXTERNAL_USDT' then
    if nullif(trim(p_network),'') is null then raise exception 'network_required'; end if;
    v_fee := coalesce(v_rate.withdrawal_fee_usdt,0);
  else
    if p_payment_method_id is null or nullif(trim(p_beneficiary_name),'') is null then raise exception 'payout_details_required'; end if;
    if not exists(select 1 from public.payment_methods where method_id=p_payment_method_id and is_active=true and category in ('WITHDRAW','BOTH')) then raise exception 'payment_method_unavailable'; end if;
    v_fee := round(p_amount_usdt * coalesce(v_rate.fee_percentage,0) / 100,8);
  end if;
  if p_amount_usdt <= v_fee then raise exception 'amount_below_fee'; end if;
  v_net := p_amount_usdt - v_fee;
  if v_type='YER_PAYOUT' then v_yer := round(v_net * v_rate.buy_rate,2); end if;

  update public.users set balance_usdt=balance_usdt-p_amount_usdt,balance=balance_usdt-p_amount_usdt where user_id=v_user.user_id;

  insert into public.withdraw_requests(reference,user_id,payout_type,amount_usdt,fee_usdt,net_usdt,amount_yer,exchange_rate,network,destination,payment_method_id,beneficiary_name,status)
  values(v_reference,v_user.user_id,v_type,p_amount_usdt,v_fee,v_net,v_yer,case when v_type='YER_PAYOUT' then v_rate.buy_rate else null end,p_network,p_destination,p_payment_method_id,p_beneficiary_name,'PENDING')
  returning withdraw_id into v_id;

  insert into public.transactions(reference,user_id,request_id,type,status,currency,amount_usdt,amount_yer,balance_after,description,metadata)
  values(v_reference,v_user.user_id,v_id,case when v_type='YER_PAYOUT' then 'YER_PAYOUT' else 'WITHDRAW' end,'PENDING','USDT',p_amount_usdt,v_yer,v_user.balance_usdt-p_amount_usdt,case when v_type='YER_PAYOUT' then 'بيع USDT واستلام ريال يمني' else 'سحب USDT عبر '||p_network end,jsonb_build_object('fee_usdt',v_fee,'destination',p_destination));

  insert into public.notifications(user_id,audience,title,message,icon,reference)
  values(v_user.user_id,'USER','تم إنشاء طلب السحب','تم حجز المبلغ والطلب '||v_reference||' بانتظار المراجعة.','fa-arrow-up',v_reference);
  insert into public.notifications(user_id,audience,title,message,icon,reference)
  values(null,'ADMIN','طلب سحب جديد','طلب '||v_reference||' بقيمة '||round(p_amount_usdt,2)||' USDT يحتاج المراجعة.','fa-money-bill-transfer',v_reference);

  return jsonb_build_object('withdraw_id',v_id,'reference',v_reference,'status','PENDING','reserved_usdt',p_amount_usdt);
end $$;

create or replace function public.lookup_transfer_recipient(p_identifier text)
returns table(user_id bigint, full_name text, masked_identifier text)
language plpgsql
security definer
set search_path = public
as $$
declare v_self bigint := public.current_profile_id();
begin
  if v_self is null then raise exception 'account_inactive'; end if;
  return query
  select u.user_id,
         u.full_name::text,
         case when lower(u.email)=lower(trim(p_identifier))
           then regexp_replace(u.email, '(^.).*(@.*$)', '\1***\2')
           else '***' || right(u.phone_number,4)
         end::text
  from public.users u
  where u.user_id<>v_self and u.is_active=1 and u.deleted_at is null
    and (lower(u.email)=lower(trim(p_identifier)) or u.phone_number=regexp_replace(trim(p_identifier),'\s','','g'))
  limit 1;
end $$;

create or replace function public.internal_transfer(p_identifier text,p_amount_usdt numeric,p_note text default null)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_sender_id bigint := public.current_profile_id();
  v_recipient_id bigint;
  v_sender_balance numeric(20,8);
  v_recipient_balance numeric(20,8);
  v_reference text := public.make_reference('TRF');
begin
  if v_sender_id is null then raise exception 'account_inactive'; end if;
  if p_amount_usdt is null or p_amount_usdt<=0 then raise exception 'invalid_amount'; end if;
  select u.user_id into v_recipient_id from public.users u
    where u.is_active=1 and u.deleted_at is null
      and (lower(u.email)=lower(trim(p_identifier)) or u.phone_number=regexp_replace(trim(p_identifier),'\s','','g'))
    limit 1;
  if v_recipient_id is null then raise exception 'recipient_not_found'; end if;
  if v_recipient_id=v_sender_id then raise exception 'cannot_transfer_to_self'; end if;

  perform pg_advisory_xact_lock(least(v_sender_id,v_recipient_id));
  perform pg_advisory_xact_lock(greatest(v_sender_id,v_recipient_id));
  select balance_usdt into v_sender_balance from public.users where user_id=v_sender_id for update;
  select balance_usdt into v_recipient_balance from public.users where user_id=v_recipient_id for update;
  if coalesce(v_sender_balance,0)<p_amount_usdt then raise exception 'insufficient_balance'; end if;

  update public.users set balance_usdt=balance_usdt-p_amount_usdt,balance=balance_usdt-p_amount_usdt where user_id=v_sender_id;
  update public.users set balance_usdt=balance_usdt+p_amount_usdt,balance=balance_usdt+p_amount_usdt where user_id=v_recipient_id;

  insert into public.transactions(reference,user_id,type,status,currency,amount_usdt,balance_after,description,metadata)
  values
    (v_reference,v_sender_id,'TRANSFER_OUT','COMPLETED','USDT',p_amount_usdt,v_sender_balance-p_amount_usdt,coalesce(p_note,'تحويل داخلي صادر'),jsonb_build_object('counterparty_user_id',v_recipient_id)),
    (v_reference,v_recipient_id,'TRANSFER_IN','COMPLETED','USDT',p_amount_usdt,v_recipient_balance+p_amount_usdt,coalesce(p_note,'تحويل داخلي وارد'),jsonb_build_object('counterparty_user_id',v_sender_id));

  insert into public.notifications(user_id,audience,title,message,icon,reference)
  values
    (v_sender_id,'USER','تم إرسال التحويل','اكتمل التحويل '||v_reference||' بقيمة '||round(p_amount_usdt,2)||' USDT.','fa-arrow-left',v_reference),
    (v_recipient_id,'USER','حوالة واردة','استلمت '||round(p_amount_usdt,2)||' USDT بالمرجع '||v_reference||'.','fa-arrow-right',v_reference);

  return jsonb_build_object('reference',v_reference,'status','COMPLETED','amount_usdt',p_amount_usdt);
end $$;

create or replace function public.submit_kyc_request(p_document_type text,p_document_number text,p_front_path text,p_back_path text,p_selfie_path text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
