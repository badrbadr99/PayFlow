create or replace function public.admin_review_kyc(p_kyc_id bigint,p_decision text,p_reason text default null)
returns void language plpgsql security definer set search_path=public as $$
declare v_admin bigint:=public.current_profile_id(); v_row public.kyc_requests%rowtype; v_decision text:=upper(p_decision);
begin
  if not public.is_admin() then raise exception 'not_authorized'; end if;
  if v_decision not in ('APPROVED','REJECTED') then raise exception 'invalid_decision'; end if;
  if v_decision='REJECTED' and nullif(trim(p_reason),'') is null then raise exception 'rejection_reason_required'; end if;
  select * into v_row from public.kyc_requests where kyc_id=p_kyc_id for update;
  if not found then raise exception 'request_not_found'; end if;
  if upper(v_row.status)<>'PENDING' then raise exception 'request_already_reviewed'; end if;
  update public.kyc_requests set status=v_decision,rejection_reason=case when v_decision='REJECTED' then p_reason else null end,reviewed_by=v_admin::text,reviewed_at=now(),updated_at=now() where kyc_id=p_kyc_id;
  update public.users set kyc_status=v_decision where user_id=v_row.user_id;
  insert into public.notifications(user_id,audience,title,message,icon,reference) values(v_row.user_id,'USER',case when v_decision='APPROVED' then 'تم توثيق حسابك' else 'يحتاج التوثيق إلى تعديل' end,case when v_decision='APPROVED' then 'اكتمل التحقق من هويتك ويمكنك الآن استخدام خدمات السحب.' else p_reason end,case when v_decision='APPROVED' then 'fa-user-check' else 'fa-id-card' end,'KYC-'||p_kyc_id);
  insert into public.audit_logs(actor_user_id,action,entity_type,entity_id,details) values(v_admin,'REVIEW_'||v_decision,'KYC',p_kyc_id::text,jsonb_build_object('reason',p_reason));
end $$;

create or replace function public.admin_set_user_status(p_user_id bigint,p_active boolean)
returns void language plpgsql security definer set search_path=public as $$
declare v_admin bigint:=public.current_profile_id();
begin
  if not public.is_admin() then raise exception 'not_authorized'; end if;
  if p_user_id=v_admin then raise exception 'cannot_disable_self'; end if;
  update public.users set is_active=case when p_active then 1 else 0 end,deleted_at=case when p_active then null else deleted_at end where user_id=p_user_id;
  if not found then raise exception 'user_not_found'; end if;
  insert into public.notifications(user_id,audience,title,message,icon) values(p_user_id,'USER',case when p_active then 'تم تفعيل حسابك' else 'تم تجميد حسابك' end,case when p_active then 'يمكنك استخدام حسابك مجددًا.' else 'تواصل مع خدمة العملاء لمعرفة التفاصيل.' end,'fa-user-lock');
  insert into public.audit_logs(actor_user_id,action,entity_type,entity_id) values(v_admin,case when p_active then 'ACTIVATE' else 'FREEZE' end,'USER',p_user_id::text);
end $$;

create or replace function public.admin_archive_user(p_user_id bigint,p_reason text)
returns void language plpgsql security definer set search_path=public as $$
declare v_admin bigint:=public.current_profile_id();
begin
  if not public.is_admin() then raise exception 'not_authorized'; end if;
