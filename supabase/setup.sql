create or replace function public.current_profile_id()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select user_id from public.users
  where auth_user_id = auth.uid() and is_active = 1 and deleted_at is null
  limit 1
$$;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.users
    where auth_user_id = auth.uid()
      and upper(role) = 'ADMIN'
      and is_active = 1
      and deleted_at is null
  )
$$;

create or replace function public.make_reference(prefix text)
returns text
language sql
volatile
set search_path = public
as $$
  select upper(prefix) || '-' || to_char(clock_timestamp(), 'YYMMDD') || '-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8))
$$;

create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.users (auth_user_id, full_name, email, phone_number, role, kyc_status, is_active, balance_usdt, balance_yer, balance, password_hash)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data->>'full_name',''), split_part(new.email,'@',1)),
    lower(new.email),
    nullif(new.raw_user_meta_data->>'phone_number',''),
    'USER', 'NOT_SUBMITTED', 1, 0, 0, 0, null
  )
  on conflict (email) do update
    set auth_user_id = excluded.auth_user_id,
        full_name = coalesce(nullif(public.users.full_name,''), excluded.full_name),
        phone_number = coalesce(public.users.phone_number, excluded.phone_number),
        password_hash = null,
        updated_at = now();
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_auth_user();

-- Link any existing Supabase Auth accounts to existing public profiles.
insert into public.users (auth_user_id, full_name, email, role, kyc_status, is_active, balance_usdt, balance_yer, balance, password_hash)
select au.id,
       coalesce(nullif(au.raw_user_meta_data->>'full_name',''), split_part(au.email,'@',1)),
       lower(au.email), 'USER', 'NOT_SUBMITTED', 1, 0, 0, 0, null
from auth.users au
where au.email is not null
on conflict (email) do update
  set auth_user_id = excluded.auth_user_id,
      password_hash = null,
      updated_at = now();

