create or replace function public.admin_review_deposit(p_deposit_id bigint,p_decision text,p_note text default null)
returns void language plpgsql security definer set search_path=public as $$
declare v_admin bigint:=public.current_profile_id(); v_row public.deposit_requests%rowtype; v_new_balance numeric(20,8); v_decision text:=upper(p_decision);
begin
  if not public.is_admin() then raise exception 'not_authorized'; end if;
  if v_decision not in ('APPROVED','REJECTED') then raise exception 'invalid_decision'; end if;
  select * into v_row from public.deposit_requests where deposit_id=p_deposit_id for update;
  if not found then raise exception 'request_not_found'; end if;
  if upper(v_row.status)<>'PENDING' then raise exception 'request_already_reviewed'; end if;
  if v_decision='APPROVED' then
    update public.users set balance_usdt=coalesce(balance_usdt,0)+v_row.net_usdt,balance=coalesce(balance_usdt,0)+v_row.net_usdt where user_id=v_row.user_id returning balance_usdt into v_new_balance;
  end if;
  update public.deposit_requests set status=v_decision,admin_note=p_note,reviewed_by=v_admin,processed_at=now() where deposit_id=p_deposit_id;
  update public.transactions set status=case when v_decision='APPROVED' then 'COMPLETED' else 'REJECTED' end,balance_after=case when v_decision='APPROVED' then v_new_balance else balance_after end,updated_at=now() where request_id=p_deposit_id and type='DEPOSIT';
  insert into public.notifications(user_id,audience,title,message,icon,reference) values(v_row.user_id,'USER',case when v_decision='APPROVED' then 'تم قبول الإيداع' else 'تم رفض الإيداع' end,case when v_decision='APPROVED' then 'أضيف '||round(v_row.net_usdt,2)||' USDT إلى رصيدك.' else coalesce(p_note,'تعذر قبول الطلب. تواصل مع الدعم.') end,case when v_decision='APPROVED' then 'fa-circle-check' else 'fa-circle-xmark' end,v_row.reference);
  insert into public.audit_logs(actor_user_id,action,entity_type,entity_id,details) values(v_admin,'REVIEW_'||v_decision,'DEPOSIT',p_deposit_id::text,jsonb_build_object('note',p_note));
end $$;

