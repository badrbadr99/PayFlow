create or replace function public.admin_search_transactions(p_query text default null,p_limit integer default 200)
returns table(transaction_id bigint,reference text,type text,status text,currency text,amount_usdt numeric,amount_yer numeric,description text,created_at timestamptz,user_id bigint,full_name text,email text)
language sql stable security definer set search_path=public as $$
  select t.transaction_id,t.reference,t.type::text,t.status::text,t.currency::text,t.amount_usdt,t.amount_yer,t.description,t.created_at,t.user_id,u.full_name::text,u.email::text
  from public.transactions t join public.users u on u.user_id=t.user_id
  where public.is_admin()
    and (nullif(trim(p_query),'') is null
      or t.reference ilike '%'||trim(p_query)||'%'
      or u.email ilike '%'||trim(p_query)||'%'
      or u.phone_number ilike '%'||trim(p_query)||'%'
      or u.full_name ilike '%'||trim(p_query)||'%')
  order by t.created_at desc
  limit least(greatest(coalesce(p_limit,200),1),500)
$$;

